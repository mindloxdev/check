export type VerificationStatus = 'verified' | 'unverified' | 'failed' | 'not_configured'
export type AttendanceSource = 'app' | 'manual' | 'offline_sync'
export type AuditAction =
  | 'check_in'
  | 'check_out'
  | 'manual_correction'
  | 'create'
  | 'update'
  | 'delete'
export type WifiMode = 'off' | 'optional' | 'required'
export type LeaveType = 'annual' | 'sick' | 'casual' | 'unpaid' | 'other'
export type ThemePreference = 'system' | 'light' | 'dark'

export type ProfileRow = {
  id: string
  user_id: string
  office_name: string
  timezone: string
  /** 'HH:mm:ss' as returned by Postgres `time`. */
  expected_check_in: string
  expected_check_out: string
  grace_period_minutes: number
  /** ISO weekdays, 1 = Monday. */
  working_days: number[]
  reporting_day: number
  wifi_mode: WifiMode
  wifi_endpoint_url: string | null
  wifi_expected_token: string | null
  wifi_timeout_ms: number
  multi_session_enabled: boolean
  overnight_enabled: boolean
  day_cutoff_hour: number
  notify_monthly_review: boolean
  notify_missing_checkout: boolean
  notify_late_arrival: boolean
  theme: ThemePreference
  created_at: string
  updated_at: string
}

export type ProfileUpdate = Partial<
  Omit<ProfileRow, 'id' | 'user_id' | 'created_at' | 'updated_at'>
>

/** The schedule frozen onto a record when it was written. */
export type PolicySnapshot = {
  timezone?: string
  expected_check_in?: string
  expected_check_out?: string
  grace_period_minutes?: number
  working_days?: number[]
  office_name?: string
  captured_at?: string
}

export type AttendanceRecordRow = {
  id: string
  user_id: string
  /** 'YYYY-MM-DD' business date in the office time zone. */
  attendance_date: string
  session_index: number
  /** ISO 8601 UTC instant, or null. */
  check_in_at: string | null
  check_out_at: string | null
  check_in_verification_status: VerificationStatus | null
  check_out_verification_status: VerificationStatus | null
  check_in_source: AttendanceSource | null
  check_out_source: AttendanceSource | null
  check_in_client_skew_seconds: number | null
  check_out_client_skew_seconds: number | null
  manual_correction: boolean
  correction_reason: string | null
  note: string | null
  policy_snapshot: PolicySnapshot
  /** Generated by the database; never sent by the client. */
  duration_minutes: number | null
  created_at: string
  updated_at: string
}

export type AuditLogRow = {
  id: string
  user_id: string
  attendance_record_id: string | null
  attendance_date: string | null
  action: AuditAction
  previous_values: Record<string, unknown> | null
  new_values: Record<string, unknown> | null
  reason: string | null
  created_at: string
}

export type HolidayRow = {
  id: string
  user_id: string
  holiday_date: string
  holiday_name: string
  created_at: string
}

export type LeaveRecordRow = {
  id: string
  user_id: string
  start_date: string
  end_date: string
  leave_type: LeaveType
  notes: string | null
  created_at: string
}

export type HolidayInsert = {
  user_id: string
  holiday_date: string
  holiday_name: string
}

export type LeaveInsert = {
  user_id: string
  start_date: string
  end_date: string
  leave_type?: LeaveType
  notes?: string | null
}

export type RateLimitRow = {
  id: number
  user_id: string
  bucket: string
  created_at: string
}

/**
 * Shape consumed by `createClient<Database>()`.
 *
 * It must structurally satisfy supabase-js's `GenericSchema`. Three details are
 * load-bearing, and getting any of them wrong makes the schema stop matching —
 * at which point supabase-js resolves `Schema` to `never` and every query
 * builder degrades to an inscrutable "not assignable to type 'never'" error
 * rather than failing loudly:
 *
 *   1. Every Row/Insert/Update must satisfy `Record<string, unknown>`. That is
 *      why the row shapes above are `type` aliases, not `interface`s: only
 *      aliases receive an implicit index signature.
 *   2. Every table must declare `Relationships`, even when empty.
 *   3. No `never` may appear as an Insert/Update type, so the read-only tables
 *      still declare real ones. Writes to those are refused by the database,
 *      where the guarantee belongs — the grants in the RLS migration revoke
 *      INSERT, UPDATE and DELETE on the audit log outright.
 */
